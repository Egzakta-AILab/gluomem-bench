def verify_execution_spec(spec_path, approval_path):
    """Read-only refusal gate before clients, receipts or run-owned stores."""
    spec_path, approval_path = Path(spec_path), Path(approval_path)
    spec_bytes = spec_path.read_bytes()
    spec = json.loads(spec_bytes)
    approval = json.loads(approval_path.read_bytes())
    if (
        spec.get("protocol")
        not in {PROTOCOL, FULL_PROTOCOL, CONTINUATION_PROTOCOL, CHAINED_PROTOCOL}
        or approval.get("approved") is not True
        or approval.get("reviewer_kind") not in {"AI-assisted", "human"}
        or approval.get("spec_sha256") != hashlib.sha256(spec_bytes).hexdigest()
    ):
        raise ValueError("exact independent execution approval required")
    files = spec.get("files")
    if not isinstance(files, list) or not files:
        raise ValueError("nonempty frozen file inventory required")
    seen = set()
    for item in files:
        path = Path(item["path"])
        if (
            not path.is_absolute()
            or str(path.resolve()) in seen
            or not path.is_file()
            or hashlib.sha256(path.read_bytes()).hexdigest() != item["sha256"]
        ):
            raise ValueError("frozen file identity/hash differs")
        seen.add(str(path.resolve()))
    if Path(spec["output_root"]).exists() or (
        spec["protocol"] == CHAINED_PROTOCOL and _setup_failure_path(spec["output_root"]).exists()
    ):
        raise FileExistsError("fresh campaign output root required")
    if spec["protocol"] == CHAINED_PROTOCOL:
        if (
            approval.get("semantic_delta_manifest_sha256")
            != spec["semantic_delta_manifest"]["sha256"]
        ):
            raise ValueError("exact reviewed semantic delta approval digest required")
        validate_chained_continuation_spec(spec)
        _validate_prior_resource_allowance(spec, require_settled=True, execution_approval=approval)
        if spec["files"] != frozen_inventory(spec["dataset"]["path"], spec["judge_source"]):
            raise ValueError("complete frozen inventory differs")
    if spec["protocol"] == CONTINUATION_PROTOCOL:
        validate_continuation_spec(spec)
        if spec["files"] != frozen_inventory(spec["dataset"]["path"], spec["judge_source"]):
            raise ValueError("complete frozen inventory differs")
    if spec["protocol"] == FULL_PROTOCOL:
        dataset = spec["dataset"]
        if dataset["name"] != "longmemeval_s":
            raise ValueError("full native LongMemEval-S required")
        source = Path(dataset["path"])
        if hashlib.sha256(source.read_bytes()).hexdigest() != dataset["sha256"]:
            raise ValueError("full dataset identity differs")
        validate_full_spec(spec, [r["question_id"] for r in json.loads(source.read_bytes())])
        if spec["files"] != frozen_inventory(source, spec["judge_source"]):
            raise ValueError("complete frozen inventory differs")
        from gluomem_bench.bench.upstream_scoring import load_longmemeval_prompt

        load_longmemeval_prompt(Path(spec["judge_source"]))
    return spec


def full_context_fits(spec, profile, tokens, input_chars):
    if type(tokens) is not int or tokens < 0:
        raise ValueError("invalid full-history tokenizer response")
    return (
        tokens + profile.output_budget("answer") + profile.schema_reserve_tokens
        <= profile.context_window
        and input_chars <= profile.max_input_chars
        and (
            spec["protocol"] not in {FULL_PROTOCOL, CONTINUATION_PROTOCOL, CHAINED_PROTOCOL}
            or tokens <= spec["evidence_token_budget"]
        )
    )


def _validate_chain_launch_process(spec):
    """Refuse ambient launch state before setup, native clients or output writes."""
    import os
    import sys

    if Path.cwd().resolve() != Path(spec["working_directory"]).resolve():
        raise ValueError("chain launch working directory differs")
    for key, value in spec["execution_environment"].items():
        if key == "unset":
            if any(name in os.environ for name in value):
                raise ValueError("chain launch unset environment differs")
        elif os.environ.get(key) != value:
            raise ValueError("chain launch environment differs")
    pinned = next((p for p in spec["files"] if Path(p["path"]).resolve() == Path(sys.executable).resolve()), None)
    if pinned is None or hashlib.sha256(Path(sys.executable).read_bytes()).hexdigest() != pinned["sha256"]:
        raise ValueError("chain launch interpreter environment differs")


def execute_longmemeval(spec_path, approval_path):
    """Execute only the explicit admitted jobs; never infer dataset/system defaults."""
    admitted_raw, admitted_approval = Path(spec_path).read_bytes(), Path(approval_path).read_bytes()
    spec = verify_execution_spec(spec_path, approval_path)
    if Path(spec_path).read_bytes() != admitted_raw or Path(approval_path).read_bytes() != admitted_approval:
        raise ValueError("execution provenance changed during admission")
    if spec["protocol"] == CHAINED_PROTOCOL and "launch_metadata" in spec:
        _validate_chain_launch_process(spec)
    continuation = spec["protocol"] in {CONTINUATION_PROTOCOL, CHAINED_PROTOCOL}
    budget = None
    if continuation:
        from gluomem_bench.bench.parallel_campaign import CampaignBudget

        debit = _validate_prior_resource_allowance(spec)
        budget = CampaignBudget(
            max_calls=spec["campaign_policy"]["max_calls"],
            max_seconds=spec["campaign_policy"]["max_seconds"],
            prior_calls=debit["calls"],
            prior_elapsed_seconds=debit["elapsed_seconds"],
        )
        budget._driver_resource_accounting = _resource_accounting(spec, debit=debit)
        budget.check()
    if spec["protocol"] == CHAINED_PROTOCOL and "launch_metadata" in spec:
        # Capture exact authenticated bytes BEFORE the first fallible setup write.
        # Later failures cannot depend on files that setup has not preserved yet.
        raw, approved = admitted_raw, admitted_approval
        if json.loads(raw) != spec or json.loads(approved).get("spec_sha256") != hashlib.sha256(raw).hexdigest():
            raise ValueError("setup provenance changed after admission")
        budget._driver_setup_provenance = (raw, approved)
        budget._driver_setup_complete = False
    try:
        return _execute_longmemeval(spec_path, approval_path, spec, budget)
    except BaseException as exc:
        if budget is not None and getattr(budget, "_driver_setup_complete", True) is False:
            return _abort_chain_setup(Path(spec["output_root"]), spec, budget, exc)
        if not continuation or not Path(spec["output_root"]).exists():
            raise
        from gluomem_bench.bench.parallel_campaign import CampaignReceiptError

        if isinstance(exc, CampaignReceiptError) and exc.receipt.get("publication") == "incomplete":
            raise
        return _abort_continuation(Path(spec["output_root"]), spec, budget, exc)


def _resource_accounting(spec, *, debit=None):
    """Labels accompany debited counters so reservations never become actuals."""
    if spec.get("prior_resource_allowance") is None:
        return {}
    return dict(resource_accounting=dict(
        protocol="longmemeval-resource-accounting@v1", prior_debit_kind="reserved",
        observed_prior_accounting=spec["prior_accounting"],
        conservative_prior_allowance=debit if debit is not None else _validate_prior_resource_allowance(spec),
        actual_additional_spend=dict(calls=None, elapsed_seconds=None, tokens=None),
        prior_resource_allowance=spec["prior_resource_allowance"],
    ))


def _setup_failure_path(root):
    root = Path(root).resolve()
    return root.with_name(root.name + ".setup-incomplete.json")


def _abort_chain_setup(root, spec, budget, exc):
    """Non-promoting terminal failure evidence, independent of locked root files.

    Only admitted in-memory provenance is used. This record cannot certify leaf
    quality, preservation or execution. The initiating exception remains cause.
    """
    from gluomem_bench.bench.parallel_campaign import CampaignReceiptError

    budget.failed = True
    raw, approved = budget._driver_setup_provenance
    result = dict(
        protocol="longmemeval-setup-incomplete@v1",
        output_root=str(root.resolve()), complete=False, execution_complete=False,
        publication="incomplete", terminal=True, completion_authority="none; setup failure evidence only",
        spec_bytes_utf8=raw.decode("utf-8"), approval_bytes_utf8=approved.decode("utf-8"),
        spec_sha256=hashlib.sha256(raw).hexdigest(), approval_sha256=hashlib.sha256(approved).hexdigest(),
        accounting=budget.snapshot(), prior_accounting=spec["prior_accounting"],
        prior_spend_uncertainty=spec["prior_spend_uncertainty"],
        receipt_failure=safe_failure_diagnostic(exc),
        **budget._driver_resource_accounting,
    )
    # Never replace the original error with cleanup/publication failures. Even
    # failed mkdir is recorded beside the exact approved root, not inside it.
    try:
        target = _setup_failure_path(root)
        with target.open("xb") as stream:
            stream.write(json.dumps(result, ensure_ascii=False, sort_keys=True).encode("utf-8"))
        if json.loads(target.read_bytes()) != result:
            raise ValueError("setup failure readback differs")
    except BaseException as publication_error:
        result["failure_publication_error"] = safe_failure_diagnostic(publication_error)
    raise CampaignReceiptError(result) from exc


def verify_setup_incomplete(out):
    """Read-only terminal failure verification; NEVER grants completion authority.

    Root snapshots may be absent/locked. The embedded exact approved spec bytes
    identify the root and all transitive provenance; validation remains unchanged.
    """
    import math

    root = Path(out).resolve()
    result = json.loads(_setup_failure_path(root).read_bytes())
    raw, approved = result["spec_bytes_utf8"].encode("utf-8"), result["approval_bytes_utf8"].encode("utf-8")
    spec, approval = json.loads(raw), json.loads(approved)
    if (
        result.get("protocol") != "longmemeval-setup-incomplete@v1"
        or spec.get("protocol") != CHAINED_PROTOCOL
        or result.get("output_root") != str(root)
        or spec.get("output_root") != str(root)
        or result.get("spec_sha256") != hashlib.sha256(raw).hexdigest()
        or result.get("approval_sha256") != hashlib.sha256(approved).hexdigest()
        or approval.get("spec_sha256") != result["spec_sha256"]
        or approval.get("approved") is not True
        or approval.get("reviewer_kind") not in {"AI-assisted", "human"}
        or approval.get("semantic_delta_manifest_sha256") != spec["semantic_delta_manifest"]["sha256"]
        or result.get("complete") is not False
        or result.get("execution_complete") is not False
        or result.get("terminal") is not True
        or result.get("publication") != "incomplete"
        or result.get("completion_authority") != "none; setup failure evidence only"
        or result.get("prior_accounting") != spec["prior_accounting"]
        or result.get("prior_spend_uncertainty") != spec["prior_spend_uncertainty"]
    ):
        raise ValueError("setup failure exact provenance/root/authority differs")
    validate_chained_continuation_spec(spec)
    prior = _validate_prior_resource_allowance(spec, require_settled=True, execution_approval=approval)
    if result.get("resource_accounting") != _resource_accounting(spec, debit=prior).get("resource_accounting"):
        raise ValueError("setup reserved versus measured labels differ")
    account = result["accounting"]
    if (
        account.get("calls") != prior["calls"]
        or account.get("prior_calls") != prior["calls"]
        or account.get("new_calls") != 0
        or account.get("prior_elapsed_seconds") != prior["elapsed_seconds"]
        or type(account.get("new_elapsed_seconds")) not in (int, float)
        or not math.isfinite(account["new_elapsed_seconds"])
        or account["new_elapsed_seconds"] < 0
        or account.get("elapsed_seconds") != prior["elapsed_seconds"] + account["new_elapsed_seconds"]
    ):
        raise ValueError("setup failure retained debit differs")
    return result


def _abort_continuation(root, spec, budget, exc):
    """Setup, scheduler, hashing and summary failures keep all attempts and leaves."""
    import copy

    from gluomem_bench.bench.parallel_campaign import CampaignReceiptError

    budget.failed = True
    result = copy.deepcopy(exc.receipt) if isinstance(exc, CampaignReceiptError) else {}
    progress = root / "coordination/progress.json"
    if not result and progress.exists():
        result = json.loads(progress.read_bytes())
    fresh = {r["job_id"]: r for r in result.get("jobs", [])}
    rows = []
    for record in spec["jobs"]:
        if record["disposition"] == "dispatch":
            row = fresh.get(
                record["job_id"],
                dict(job_id=record["job_id"], history_id=record["history_id"], status="unrun"),
            )
            try:
                row["artifact_sha256"] = _job_artifacts(root, record)
            except Exception as error:
                row["artifact_hash_failure"] = safe_failure_diagnostic(error)
        else:
            row = copy.deepcopy(record["prior_row"])
        row.update(
            disposition=record["disposition"],
            cohort=_row_cohort(spec, record),
        )
        rows.append(row)
    result.update(
        jobs=rows,
        complete=False,
        execution_complete=False,
        publication="incomplete",
        accounting=budget.snapshot(),
        receipt_failure=safe_failure_diagnostic(exc),
        **getattr(budget, "_driver_resource_accounting", {}),
    )
    if spec["protocol"] == CHAINED_PROTOCOL:
        result.update(
            spec_sha256=hashlib.sha256((root / "execution-spec.json").read_bytes()).hexdigest(),
            frozen_inputs=[dict(f, snapshot="frozen-inputs/" + f["sha256"]) for f in spec["files"]],
            reuse_receipt=spec["reuse_receipt"],
            cognee_unrun=spec["cognee_unrun"],
            cohorts=spec["cohorts"],
            prior_spend_uncertainty=spec["prior_spend_uncertainty"],
        )
    errors = []
    for path in (
        root / "root-status.pending.json",
        root / "campaign-result.json",
        root / "root-status.json",
    ):
        try:
            path.unlink(missing_ok=True)
        except OSError as error:
            errors.append(safe_failure_diagnostic(error))
    try:
        (root / "root-status.json").write_bytes(
            json.dumps(result, ensure_ascii=False, sort_keys=True).encode()
        )
    except OSError as error:
        errors.append(safe_failure_diagnostic(error))
    if errors:
        result["cleanup_errors"] = errors
    raise CampaignReceiptError(result) from exc


def _execute_longmemeval(spec_path, approval_path, spec, budget):
    continuation = spec["protocol"] in {CONTINUATION_PROTOCOL, CHAINED_PROTOCOL}
    from gluomem_bench.bench.upstream_scoring import load_longmemeval_prompt

    # An inventory hash alone does not establish compatibility with the pinned scorer.
    # Reject once, before clients, scheduling, or any run-owned outputs exist.
    load_longmemeval_prompt(Path(spec["judge_source"]))
    import os
    from dataclasses import asdict, replace
    from types import SimpleNamespace

    from gluomem_bench.bench.adapters.longmemeval import LongMemEvalAdapter
    from gluomem_bench.bench.baselines import transcript
    from gluomem_bench.bench.embedding_runtime import EmbeddingRecipe, RemoteEmbedder
    from gluomem_bench.bench.evidence_retriever import RawCampaignRetriever
    from gluomem_bench.bench.parallel_campaign import CampaignPolicy, Job, run_jobs
    from gluomem_bench.bench.rack import RackClient, RackProfile, controlled_config
    from gluomem_bench.bench.suite_campaign import reader_messages, run_history, verify_history

    root = Path(spec["output_root"])
    profile = RackProfile.model_validate(spec["profile"])
    if profile.profile_version not in {"role-budgets-v5", "role-budgets-v6"}:
        raise ValueError("explicit role-budgets-v5 or role-budgets-v6 profile required")
    dataset = spec["dataset"]
    if dataset["name"] != "longmemeval_s":
        raise ValueError("this driver admits only the declared LongMemEval-S slice")
    source = Path(dataset["path"])
    if hashlib.sha256(source.read_bytes()).hexdigest() != dataset["sha256"]:
        raise ValueError("dataset differs from execution specification")
    cfg = controlled_config(profile, data=source, sha256=dataset["sha256"])
    cfg = cfg.with_overrides(spec["config_overrides"])
    adapter = LongMemEvalAdapter(cfg, dataset["name"])
    adapter.verify()
    canonical = {sample.id: sample for sample in adapter.load()}
    selected = spec["sample_ids"]
    if not selected or len(set(selected)) != len(selected) or not set(selected) <= canonical.keys():
        raise ValueError("invalid or duplicate frozen sample selection")
    raw_conversations = {
        conv.conv_id: conv for conv in adapter.conversations() if conv.conv_id in selected
    }
    conversations = {
        key: replace(
            conv,
            sessions=sorted(conv.sessions, key=lambda session: (session.date_time, session.index)),
        )
        for key, conv in raw_conversations.items()
    }
    # Read-only cached data seam: no repeated construction of every released haystack.
    admitted_adapter = SimpleNamespace(
        name=adapter.name,
        sha=adapter.sha,
        path=adapter.path,
        verify=adapter.verify,
        load=lambda: [canonical[key] for key in selected],
        conversations=lambda: list(conversations.values()),
    )
    encoder = RemoteEmbedder(
        spec["embedding_url"], recipe=EmbeddingRecipe(**spec["embedding_recipe"])
    )
    systems = set(spec["systems"])
    supported = {"no_memory", "bm25", "dense", "hybrid", "full_context", "gluomem", "mem0"}
    if not systems or not systems <= supported:
        raise ValueError("unadmitted system in execution specification")
    jobs = []
    bindings = {}
    for record in spec["jobs"]:
        if continuation and record["disposition"] != "dispatch":
            continue
        if record["system"] not in systems or record["sample_id"] not in selected:
            raise ValueError("job differs from admitted system/sample matrix")
        job = Job(
            record["job_id"],
            record["history_id"],
            Path(record["output"]),
            record["call_budget"],
            record["seconds_budget"],
        )
        if not job.output.is_relative_to(root):
            raise ValueError("job output escapes fresh campaign root")
        jobs.append(job)
        bindings[job.job_id] = record
    matrix = [(record["system"], record["sample_id"]) for record in spec["jobs"]]
    if not continuation and (
        len(set(matrix)) != len(matrix)
        or set(matrix) != {(system, sample) for system in systems for sample in selected}
    ):
        raise ValueError("frozen job matrix is incomplete or duplicated")
    # All native import-time providers are isolated in this child process only.
    if spec["protocol"] == CHAINED_PROTOCOL and "launch_metadata" in spec:
        # The effective environment IS the frozen launch contract, not a second
        # set of native defaults silently applied after admission.
        _validate_chain_launch_process(spec)
    else:
        # Preserve the original setup contract for old protocols.
        os.environ.pop("OPENAI_API_KEY", None)
        os.environ.pop("OPENROUTER_API_KEY", None)
        os.environ["MEM0_TELEMETRY"] = "False"
        os.environ["MEM0_DIR"] = str(root / "native-mem0-home")
        os.environ["GLUOMEM_RACK_API_KEY"] = "local-endpoint-placeholder"
    judge_source = Path(spec["judge_source"])

    def run_job(job, context):
        record = bindings[job.job_id]
        system = record["system"]
        sample = canonical[record["sample_id"]]
        conv = conversations[sample.conv_id]
        active_adapter, conv, source_bindings = _model_input_history(
            admitted_adapter, conv, system, spec.get("source_identifier_policy")
        )
        source_mapping = None
        if source_bindings:
            mapping_path = root / "source-id-mappings" / f"{job.job_id}.json"
            mapping_path.parent.mkdir(parents=True, exist_ok=True)
            material = (
                json.dumps(
                    [asdict(binding) for binding in source_bindings],
                    ensure_ascii=False,
                    sort_keys=True,
                )
                + "\n"
            ).encode()
            with mapping_path.open("xb") as stream:
                stream.write(material)
            source_mapping = {
                "path": str(mapping_path),
                "sha256": hashlib.sha256(material).hexdigest(),
                "policy": spec["source_identifier_policy"],
            }
        if system == "full_context":
            admission_path = root / "context-admission" / f"{job.job_id}.jsonl"
            if admission_path.exists():
                raise FileExistsError("fresh context-admission receipt required")
            admission = RackClient(profile, receipt=admission_path, budget=context)
            try:
                messages = reader_messages(sample.reader_question, transcript(conv))
                tokens = admission.prompt_token_count(messages)
                if type(tokens) is not int or tokens < 0:
                    raise ValueError("invalid full-history tokenizer response")
                if not full_context_fits(
                    spec, profile, tokens, len(json.dumps(messages, ensure_ascii=False))
                ):
                    return {
                        "quality_status": "not_applicable_context_overflow",
                        "prompt_tokens": tokens,
                        "generation_calls": 0,
                    }
                admission.admit_context(
                    tokens,
                    output_budget=profile.output_budget("answer"),
                    input_chars=len(json.dumps(messages, ensure_ascii=False)),
                )
            finally:
                admission.close()

        factory = None
        if system in {"bm25", "dense", "hybrid"}:

            def factory(active_cfg, active_conv, answer):
                retriever = RawCampaignRetriever(
                    active_cfg,
                    active_conv,
                    answer,
                    mode=system,
                    embedder=encoder,
                    chunk_chars=spec["raw_chunk_chars"],
                )
                metadata = retriever.manifest_extra()
                (job.output / "raw-backend.json").write_bytes(
                    (json.dumps(metadata, sort_keys=True, indent=2) + "\n").encode()
                )
                chunks = [
                    {"id": item.id, "text": item.text, "provenance": dict(item.provenance)}
                    for item in retriever.chunks
                ]
                (job.output / "raw-inputs.json").write_bytes(
                    (json.dumps(chunks, ensure_ascii=False, sort_keys=True) + "\n").encode()
                )
                return retriever

        result = run_history(
            cfg=cfg,
            adapter=active_adapter,
            samples=[sample],
            profile=profile,
            out=job.output,
            system=system,
            judge_source=judge_source,
            embedder=encoder,
            outer_budget=context,
            evidence_token_budget=spec["evidence_token_budget"],
            retriever_factory=factory,
        )
        expected = {"dataset": adapter.name, "system": system, "sample_ids": [sample.id]}
        if system == "mem0":
            from mem0.configs.prompts import ADDITIVE_EXTRACTION_PROMPT

            from gluomem_bench.bench.mem0 import _mem0_digest, _session_messages

            expected.update(
                {
                    "mem0_source_inputs_sha256": _mem0_digest(
                        [
                            {
                                "session_index": session.index,
                                "session_date": session.date_time.isoformat(),
                                "messages": _session_messages(session),
                            }
                            for session in conv.sessions
                        ]
                    ),
                    "mem0_extractor_system_sha256": hashlib.sha256(
                        ADDITIVE_EXTRACTION_PROMPT.encode()
                    ).hexdigest(),
                    "profile_sha256": hashlib.sha256(
                        profile.model_dump_json().encode()
                    ).hexdigest(),
                    "dataset_sha256": adapter.sha,
                }
            )
        verify_history(
            job.output, expected_job=expected, require_real=True, judge_source=judge_source
        )
        saved = json.loads((job.output / "effective-config.json").read_bytes())
        if saved != cfg.model_dump(mode="json"):
            raise ValueError("actual configuration differs from frozen driver inputs")
        rows = json.loads((job.output / "predictions.json").read_bytes())
        if rows[0]["sample"] != json.loads(json.dumps(asdict(sample))):
            raise ValueError("actual sample differs from frozen native data")
        return {
            "quality_status": "complete_verified",
            "summary": result,
            "expected_job": expected,
            "source_identifier_mapping": source_mapping,
        }

    root.mkdir(parents=True, exist_ok=False)
    if spec["protocol"] == CHAINED_PROTOCOL and "launch_metadata" in spec:
        _seed_chain_cache_assets(spec)
    (root / "execution-spec.json").write_bytes(Path(spec_path).read_bytes())
    (root / "independent-approval.json").write_bytes(Path(approval_path).read_bytes())
    (root / "root-status.json").write_bytes(
        json.dumps(
            dict(
                complete=False,
                status="running",
                completion_authority="root-status.json",
                expected_job_ids=[j.job_id for j in jobs],
            )
        ).encode()
    )
    frozen_inputs = preserve_frozen_inputs(spec, root)
    if budget is not None and hasattr(budget, "_driver_setup_complete"):
        budget._driver_setup_complete = True
    from threading import Event

    cancelled = Event()

    def isolated_run(job, context):
        try:
            return run_job(job, context)
        except Exception:
            if context.budget.failed:
                cancelled.set()
            raise

    scheduler_kwargs = {"budget": budget} if continuation else {}
    result = run_jobs(
        jobs,
        policy=CampaignPolicy(**spec["campaign_policy"]),
        out=root / "coordination",
        run_job=isolated_run,
        cancel=cancelled,
        **scheduler_kwargs,
    )
    result["frozen_inputs"] = frozen_inputs
    for row in result["jobs"]:
        record = bindings[row["job_id"]]
        if continuation:
            row["artifact_sha256"] = _job_artifacts(root, record, budget=budget)
            continue
        paths = list(Path(record["output"]).rglob("*"))
        paths += [
            root / "source-id-mappings" / f"{row['job_id']}.json",
            root / "context-admission" / f"{row['job_id']}.jsonl",
        ]
        row["artifact_sha256"] = {
            p.relative_to(root).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest()
            for p in paths
            if p.is_file()
        }
    result["scope"] = spec.get("scope", "development pilot, not full five-family campaign")
    result["complete"] = all(
        row["status"] == "complete" and row["result"]["quality_status"] == "complete_verified"
        for row in result["jobs"]
    )
    result["completion_authority"] = "root-status.json; leaf manifests alone do not admit jobs"
    result["blocked_conditions"] = spec.get("blocked_conditions", [])
    result["spec_sha256"] = hashlib.sha256(Path(spec_path).read_bytes()).hexdigest()
    if continuation:
        return _finish_continuation(root, spec, result, budget)
    material = (json.dumps(result, ensure_ascii=False, sort_keys=True, indent=2) + "\n").encode()
    try:
        (root / "campaign-result.json").write_bytes(material)
        (root / "root-status.json").write_bytes(material)
    except Exception as exc:
        from gluomem_bench.bench.parallel_campaign import CampaignReceiptError

        result.update(
            complete=False, receipt_failure=safe_failure_diagnostic(exc)
        )
        raise CampaignReceiptError(result) from exc
    return result


def preserve_frozen_inputs(spec, root):
    """Content-addressed recoverable bytes; perform before any model dispatch."""
    import shutil

    root = Path(root)
    objects = root / "frozen-inputs"
    objects.mkdir()
    records = []
    for item in spec.get("files", []):
        target = objects / item["sha256"]
        if not target.exists():
            shutil.copyfile(item["path"], target)
        if hashlib.sha256(target.read_bytes()).hexdigest() != item["sha256"]:
            raise ValueError("frozen input snapshot hash differs")
        records.append(dict(item, snapshot=target.relative_to(root).as_posix()))
    return records


def _job_artifacts(root, record, budget=None):
    paths = list(Path(record["output"]).rglob("*"))
    paths += [
        root / "source-id-mappings" / f"{record['job_id']}.json",
        root / "context-admission" / f"{record['job_id']}.jsonl",
    ]
    digests = {}
    for path in paths:
        if budget is not None:
            budget.check()
        if path.is_file():
            digests[path.relative_to(root).as_posix()] = hashlib.sha256(
                path.read_bytes()
            ).hexdigest()
    if budget is not None:
        budget.check()
    return digests


def _row_cohort(spec, record):
    if spec["protocol"] == CHAINED_PROTOCOL:
        return spec["new_cohort"] if record["disposition"] == "dispatch" else record["prior_cohort"]
    return "fresh" if record["disposition"] == "dispatch" else "legacy"


def _continuation_summary(spec, rows):
    """No pooled quality: legacy and fresh machine-score observations stay separate."""
    from collections import Counter

    records = {r["job_id"]: r for r in spec["jobs"]}
    scores = {k: [] for k in spec["cohorts"] if k != "pool_quality"}
    for row in rows:
        record = records[row["job_id"]]
        if (
            row["status"] == "complete"
            and row.get("result", {}).get("quality_status") == "complete_verified"
        ):
            cohort = _row_cohort(spec, record)
            scores[cohort].append(
                dict(
                    job_id=row["job_id"],
                    sample_id=record["sample_id"],
                    system=record["system"],
                    scores=json.loads((Path(record["output"]) / "scores.json").read_bytes()),
                )
            )
    return dict(
        dispositions=dict(Counter(r["disposition"] for r in spec["jobs"])),
        states=dict(Counter(r["status"] for r in rows)),
        quality_by_cohort=scores,
        cognee_unrun=len(spec["cognee_unrun"]),
    )


def _verify_continuation_metadata(root, spec, result, budget=None):
    import copy
    import math

    chained = spec["protocol"] == CHAINED_PROTOCOL
    incomplete = chained and result.get("publication") == "incomplete"
    if chained and result.get("prior_spend_uncertainty") != spec["prior_spend_uncertainty"]:
        raise ValueError("prior spend uncertainty binding differs")

    if [r["path"] for r in result["frozen_inputs"]] != [r["path"] for r in spec["files"]] or len(
        {r["path"] for r in spec["files"]}
    ) != len(spec["files"]):
        raise ValueError("exact frozen input snapshot inventory differs")
    for item in spec["files"]:
        if budget is not None:
            budget.check()
        _pinned_snapshot(root, spec, result, item["path"])
    if [r["job_id"] for r in result["jobs"]] != [r["job_id"] for r in spec["jobs"]]:
        raise ValueError("exact continuation root rows differ")
    fresh = []
    for record, row in zip(spec["jobs"], result["jobs"], strict=True):
        cohort = _row_cohort(spec, record)
        if row.get("disposition") != record["disposition"] or row.get("cohort") != cohort:
            raise ValueError("root disposition/cohort differs")
        if record["disposition"] != "dispatch":
            expected = copy.deepcopy(record["prior_row"])
            expected.update(disposition=record["disposition"], cohort=cohort)
            if row != expected:
                raise ValueError("immutable prior row/spend differs")
        else:
            fresh.append(row)
            if row.get("artifact_sha256") != _job_artifacts(root, record, budget=budget):
                raise ValueError("exact leaf artifact hash inventory differs")
            if row["status"] not in {"complete", "failed", "cancelled", "unrun"}:
                raise ValueError("nonterminal continuation row")
            actual_calls = 0
            for name in ("calls.jsonl", "production-raw.jsonl"):
                path = Path(record["output"]) / name
                receipts = (
                    [json.loads(line) for line in path.read_bytes().splitlines() if line]
                    if path.exists()
                    else []
                )
                actual_calls += sum(
                    (
                        receipt.get("method") == "POST"
                        and receipt.get("url", "").endswith("/chat/completions")
                    )
                    if name == "calls.jsonl"
                    else "ordinal" in receipt
                    for receipt in receipts
                )
            if actual_calls != row.get("calls", 0):
                raise ValueError("actual new request spend differs from scheduler")
    cleaned = [
        {k: v for k, v in r.items() if k not in {"artifact_sha256", "disposition", "cohort"}}
        for r in fresh
    ]
    progress = root / "coordination/progress.json"
    if progress.exists():
        coordination = json.loads(progress.read_bytes())
    elif incomplete and all(r["status"] == "unrun" and r.get("calls", 0) == 0 for r in fresh):
        coordination = dict(
            jobs=cleaned,
            accounting=dict(
                new_elapsed_seconds=0, elapsed_seconds=spec["prior_accounting"]["elapsed_seconds"]
            ),
        )
    else:
        raise ValueError("missing actual scheduler evidence")
    if coordination["jobs"] != cleaned:
        raise ValueError("actual scheduler rows/spend differ")
    calls = sum(r.get("calls", 0) for r in fresh)
    prior = _validate_prior_resource_allowance(spec)
    if result.get("resource_accounting") != _resource_accounting(spec, debit=prior).get("resource_accounting"):
        raise ValueError("root reserved versus measured labels differ")
    accounting = result["accounting"]
    if (
        any(type(r.get("calls", 0)) is not int or r.get("calls", 0) < 0 for r in fresh)
        or accounting.get("calls") != prior["calls"] + calls
        or accounting.get("prior_calls") != prior["calls"]
        or accounting.get("new_calls") != calls
        or accounting.get("prior_elapsed_seconds") != prior["elapsed_seconds"]
        or not math.isfinite(accounting["new_elapsed_seconds"])
        or accounting["elapsed_seconds"]
        != prior["elapsed_seconds"] + accounting["new_elapsed_seconds"]
        or accounting["new_elapsed_seconds"] < coordination["accounting"]["new_elapsed_seconds"]
        or not math.isfinite(accounting["elapsed_seconds"])
        or accounting["elapsed_seconds"] < coordination["accounting"]["elapsed_seconds"]
        or (
            not incomplete
            and accounting["elapsed_seconds"] > spec["campaign_policy"]["max_seconds"]
        )
        or accounting["calls"] > spec["campaign_policy"]["max_calls"]
    ):
        raise ValueError("actual prior/new accounting differs")
    execution_complete = all(
        r["status"] == "complete"
        and r.get("result", {}).get("quality_status")
        in {"complete_verified", "not_applicable_context_overflow"}
        for r in fresh
    )
    if (
        result["complete"] is not False
        or result["execution_complete"] != (False if incomplete else execution_complete)
        or result["publication"] != ("incomplete" if incomplete else "verified")
        or result["reuse_receipt"] != spec["reuse_receipt"]
        or result["cognee_unrun"] != spec["cognee_unrun"]
        or result["cohorts"] != spec["cohorts"]
        or (not incomplete and result["summary"] != _continuation_summary(spec, result["jobs"]))
    ):
        raise ValueError("root authority/counts/scoring/cohorts differ")
    if incomplete and (root / "campaign-result.json").exists():
        raise ValueError("incomplete checkpoint cannot retain a published report")


def _verify_continuation_na(root, spec, record, row, native):
    from gluomem_bench.bench.baselines import transcript
    from gluomem_bench.bench.suite_campaign import reader_messages

    _, profile, samples, conversations, _ = native
    sample = samples[record["sample_id"]]
    messages = reader_messages(sample.reader_question, transcript(conversations[sample.conv_id]))
    trace = [
        json.loads(line)
        for line in (root / "context-admission" / f"{record['job_id']}.jsonl")
        .read_bytes()
        .splitlines()
    ]
    tokens = row.get("result", {}).get("prompt_tokens")
    if (
        record["system"] != "full_context"
        or row.get("calls", 0) != 0
        or row["result"].get("quality_status") != "not_applicable_context_overflow"
        or len(trace) != 1
        or trace[0].get("status") != 200
        or trace[0].get("method") != "POST"
        or not trace[0].get("url", "").endswith("/tokenize")
        or trace[0].get("request", {}).get("model") != profile.model
        or trace[0].get("request", {}).get("messages") != messages
        or trace[0].get("response", {}).get("count") != tokens
        or full_context_fits(spec, profile, tokens, len(json.dumps(messages, ensure_ascii=False)))
    ):
        raise ValueError("unverified policy N/A promotion")


def _finish_continuation(root, spec, result, budget):
    """Keep all old attempts, then stage/full-verify/readback/atomically publish."""
    import copy

    fresh = {r["job_id"]: r for r in result["jobs"]}
    rows = []
    for record in spec["jobs"]:
        row = copy.deepcopy(
            fresh[record["job_id"]] if record["disposition"] == "dispatch" else record["prior_row"]
        )
        row.update(
            disposition=record["disposition"],
            cohort=_row_cohort(spec, record),
        )
        rows.append(row)
    result.update(
        jobs=rows,
        complete=False,
        execution_complete=all(
            r["status"] == "complete"
            and r.get("result", {}).get("quality_status")
            in {"complete_verified", "not_applicable_context_overflow"}
            for r in fresh.values()
        ),
        reuse_receipt=spec["reuse_receipt"],
        cognee_unrun=spec["cognee_unrun"],
        cohorts=spec["cohorts"],
    )
    result.update(getattr(budget, "_driver_resource_accounting", {}))
    if spec["protocol"] == CHAINED_PROTOCOL:
        result["prior_spend_uncertainty"] = spec["prior_spend_uncertainty"]
    result["summary"] = _continuation_summary(spec, rows)
    return _publish_continuation(root, result, budget)


def _publish_continuation(root, result, budget):
    """Only root-status is authoritative; even post-promotion faults revoke it."""
    import os

    from gluomem_bench.bench.parallel_campaign import CampaignReceiptError

    staged, authority, report = (
        root / "root-status.pending.json",
        root / "root-status.json",
        root / "campaign-result.json",
    )

    def material(value):
        return (
            json.dumps(value, ensure_ascii=False, sort_keys=True, allow_nan=False, indent=2) + "\n"
        ).encode()

    try:
        result["accounting"] = budget.snapshot()
        checkpoint = dict(
            result, complete=False, execution_complete=False, publication="incomplete"
        )
        authority.write_bytes(material(checkpoint))
        budget.check()
        result["publication"] = "verified"
        data = material(result)
        staged.write_bytes(data)
        budget.check()
        verify_campaign(root, candidate_path=staged, budget=budget)
        budget.check()
        if staged.read_bytes() != data:
            raise ValueError("staged root readback differs")
        budget.check()
        report.write_bytes(data)
        budget.check()
        if report.read_bytes() != data:
            raise ValueError("campaign report readback differs")
        budget.check()
        os.replace(staged, authority)
        budget.check()
        if authority.read_bytes() != data:
            raise ValueError("promoted root readback differs")
        budget.check()
        return result
    except BaseException as exc:
        budget.failed = True
        result.update(
            complete=False,
            execution_complete=False,
            publication="incomplete",
            accounting=budget.snapshot(),
            receipt_failure=safe_failure_diagnostic(exc),
        )
        cleanup_errors = []
        for path in (staged, report, authority):
            try:
                path.unlink(missing_ok=True)
            except OSError as error:
                cleanup_errors.append(safe_failure_diagnostic(error))
        try:
            authority.write_bytes(material(result))
        except OSError as error:
            cleanup_errors.append(safe_failure_diagnostic(error))
        if cleanup_errors:
            result["cleanup_errors"] = cleanup_errors
        # A locked promoted authority must never hide revocation. The v4
        # reader gives this independently writable incomplete receipt priority.
        try:
            revoked = root / "root-incomplete.json"
            data = material(result)
            revoked.write_bytes(data)
            if revoked.read_bytes() != data:
                raise OSError("incomplete revocation readback differs")
        except OSError as error:
            result.setdefault("cleanup_errors", []).append(safe_failure_diagnostic(error))
        raise CampaignReceiptError(result) from exc


def _pinned_snapshot(root, spec, result, original):
    """Resolve recoverable bytes against the approved spec, not root declarations."""
    pins = [r for r in spec["files"] if r["path"] == original]
    copies = [r for r in result["frozen_inputs"] if r["path"] == original]
    if len(pins) != 1 or len(copies) != 1 or copies[0]["sha256"] != pins[0]["sha256"]:
        raise ValueError("missing or different frozen input binding")
    path = root / copies[0]["snapshot"]
    if (
        not path.resolve().is_relative_to(root.resolve())
        or hashlib.sha256(path.read_bytes()).hexdigest() != pins[0]["sha256"]
    ):
        raise ValueError("frozen input snapshot hash differs")
    return path


def _native_review_inputs(root, spec, result):
    """Offline reconstruction phase; leaf rescore itself remains dataset-free.

    No installed Mem0 import or execution of archived code is needed: its pinned
    prompt is a literal. The production adapter/config and message serialization
    reconstruct exactly the chronological, date-prefixed canonical protocol.
    """
    import ast
    from dataclasses import replace

    from gluomem_bench.bench.adapters.longmemeval import LongMemEvalAdapter
    from gluomem_bench.bench.rack import RackProfile, controlled_config

    source = _pinned_snapshot(root, spec, result, spec["dataset"]["path"])
    if hashlib.sha256(source.read_bytes()).hexdigest() != spec["dataset"]["sha256"]:
        raise ValueError("native dataset digest differs from spec")
    rows = json.loads(source.read_bytes())
    if spec["protocol"] == FULL_PROTOCOL:
        validate_full_spec(spec, [r["question_id"] for r in rows])
    profile = RackProfile.model_validate(spec["profile"])
    cfg = controlled_config(
        profile, data=Path(spec["dataset"]["path"]), sha256=spec["dataset"]["sha256"]
    )
    cfg = cfg.with_overrides(spec["config_overrides"])
    adapter = LongMemEvalAdapter(cfg, spec["dataset"]["name"], path=source)
    adapter.verify()
    complete_ids = {
        r["job_id"]
        for r in result["jobs"]
        if r["status"] == "complete"
        and (
            r["result"]["quality_status"] == "complete_verified"
            or spec["protocol"] in {CONTINUATION_PROTOCOL, CHAINED_PROTOCOL}
        )
    }
    wanted = {r["sample_id"] for r in spec["jobs"] if r["job_id"] in complete_ids}
    adapter._raw = [r for r in rows if r["question_id"] in wanted]
    samples = {s.id: s for s in adapter.load()}
    conversations = {
        c.conv_id: replace(c, sessions=sorted(c.sessions, key=lambda s: (s.date_time, s.index)))
        for c in adapter.conversations()
    }
    prompts = [
        r["path"]
        for r in spec["files"]
        if r["path"].replace("\\", "/").endswith("/mem0/configs/prompts.py")
    ]
    extractor = None
    if any(r["system"] == "mem0" and r["sample_id"] in wanted for r in spec["jobs"]):
        if len(prompts) != 1:
            raise ValueError("unique pinned Mem0 extractor source required")
        tree = ast.parse(_pinned_snapshot(root, spec, result, prompts[0]).read_bytes())
        values = [
            ast.literal_eval(node.value)
            for node in tree.body
            if isinstance(node, ast.Assign)
            and any(
                isinstance(t, ast.Name) and t.id == "ADDITIVE_EXTRACTION_PROMPT"
                for t in node.targets
            )
        ]
        if len(values) != 1 or not isinstance(values[0], str):
            raise ValueError("pinned Mem0 extractor must be one literal")
        extractor = hashlib.sha256(values[0].encode()).hexdigest()
    return cfg, profile, samples, conversations, extractor


def verify_campaign(out, *, candidate_path=None, budget=None, _ancestry=()):
    """Read-only corrected root interface; reconstruct pinned native inputs first.

    Old producers/roots remain immutable. Use verify_campaign_reuse_v2 to bind an
    independent review to externally supplied original spec/root/archive hashes.
    """
    from gluomem_bench.bench.suite_campaign import verify_history

    if budget is not None:
        budget.check()
    root = Path(out)
    if _setup_failure_path(root).exists():
        # Setup-failure evidence takes precedence even if root files are absent,
        # unreadable or a stale complete status could not be revoked in-place.
        return verify_setup_incomplete(root)
    raw = (root / "execution-spec.json").read_bytes()
    spec = json.loads(raw)
    revoked = root / "root-incomplete.json"
    selected = (
        revoked
        if spec.get("protocol") == CHAINED_PROTOCOL and revoked.exists()
        else root / "root-status.json"
    )
    result = json.loads((Path(candidate_path) if candidate_path else selected).read_bytes())
    continuation = spec.get("protocol") in {CONTINUATION_PROTOCOL, CHAINED_PROTOCOL}
    if continuation:
        if spec["protocol"] == CHAINED_PROTOCOL:
            validate_chained_continuation_spec(spec, budget=budget, ancestry=_ancestry)
        else:
            validate_continuation_spec(spec)
        if budget is not None:
            budget.check()
        _verify_continuation_metadata(root, spec, result, budget=budget)
    if spec.get("protocol") == FULL_PROTOCOL:
        validate_full_spec(spec, spec["sample_ids"])
    approval = json.loads((root / "independent-approval.json").read_bytes())
    if spec.get("prior_resource_allowance") is not None:
        _validate_prior_resource_allowance(spec, execution_approval=approval)
    if (
        spec.get("protocol") == CHAINED_PROTOCOL
        and approval.get("semantic_delta_manifest_sha256")
        != spec["semantic_delta_manifest"]["sha256"]
    ):
        raise ValueError("saved exact semantic delta approval binding differs")
    if (
        hashlib.sha256(raw).hexdigest() != result.get("spec_sha256")
        or approval.get("spec_sha256") != result["spec_sha256"]
        or approval.get("approved") is not True
        or [r["job_id"] for r in result["jobs"]] != [r["job_id"] for r in spec["jobs"]]
    ):
        raise ValueError("root authority/exact frozen matrix mismatch")
    planned = {r["job_id"]: r for r in spec["jobs"]}
    native = None
    if (
        continuation
        or spec.get("protocol") == FULL_PROTOCOL
        or any(r["system"] == "mem0" for r in spec["jobs"])
    ):
        native = _native_review_inputs(root, spec, result)
    for row in result["jobs"]:
        if budget is not None:
            budget.check()
        record = planned[row["job_id"]]
        if continuation and record["disposition"] != "dispatch":
            continue
        for name, expected in row["artifact_sha256"].items():
            path = root / name
            if (
                not path.resolve().is_relative_to(root.resolve())
                or hashlib.sha256(path.read_bytes()).hexdigest() != expected
            ):
                raise ValueError("root job artifact hash mismatch")
        if row["status"] == "complete" and row["result"]["quality_status"] == "complete_verified":
            record = planned[row["job_id"]]
            expected = dict(
                dataset=spec["dataset"]["name"],
                system=record["system"],
                sample_ids=[record["sample_id"]],
            )
            if native is not None:
                from dataclasses import asdict

                cfg, profile, samples, conversations, extractor = native
                sample = samples[record["sample_id"]]
                leaf = Path(record["output"])
                if json.loads((leaf / "effective-config.json").read_bytes()) != cfg.model_dump(
                    mode="json"
                ):
                    raise ValueError("actual configuration differs from frozen driver inputs")
                saved = json.loads((leaf / "predictions.json").read_bytes())
                if len(saved) != 1 or saved[0]["sample"] != json.loads(json.dumps(asdict(sample))):
                    raise ValueError("actual sample differs from frozen native data")
                if record["system"] == "mem0":
                    from gluomem_bench.bench.mem0 import _mem0_digest, _session_messages

                    expected.update(
                        mem0_source_inputs_sha256=_mem0_digest(
                            [
                                dict(
                                    session_index=s.index,
                                    session_date=s.date_time.isoformat(),
                                    messages=_session_messages(s),
                                )
                                for s in conversations[sample.conv_id].sessions
                            ]
                        ),
                        mem0_extractor_system_sha256=extractor,
                        profile_sha256=hashlib.sha256(
                            profile.model_dump_json().encode()
                        ).hexdigest(),
                        dataset_sha256=spec["dataset"]["sha256"],
                    )
                if row["result"].get("expected_job") != expected:
                    raise ValueError("root expected_job differs from reconstructed native bindings")
            judge = next(
                (
                    root / r["snapshot"]
                    for r in result["frozen_inputs"]
                    if r["path"] == spec["judge_source"]
                ),
                Path(spec["judge_source"]),
            )
            replayed_summary = verify_history(
                Path(record["output"]), expected_job=expected, require_real=True, judge_source=judge
            )
            if (
                spec.get("protocol") == CHAINED_PROTOCOL
                and replayed_summary != row["result"]["summary"]
            ):
                raise ValueError("exact saved QA summary replay differs")
            if continuation and json.loads((Path(record["output"]) / "usage.json").read_bytes())[
                "generation_calls"
            ] != row.get("calls", 0):
                raise ValueError("actual new leaf spend differs from coordinator")
        elif continuation and row["status"] == "complete":
            _verify_continuation_na(root, spec, record, row, native)
    complete = all(
        r["status"] == "complete" and r["result"]["quality_status"] == "complete_verified"
        for r in result["jobs"]
    )
    if result["complete"] != (False if continuation else complete):
        raise ValueError("root completion differs from exact verified matrix")
    if budget is not None:
        budget.check()
    return result


def verify_campaign_reuse_v2(out, *, spec_sha256, root_sha256, archive_path, archive_sha256):
    """Explicit read-only review of post-exit v1 evidence under corrected v2 API.

    Supply independently retained hashes, not hashes fetched from an untrusted
    root. Returns a review receipt only; never writes or promotes original jobs,
    retries generation, changes full-history policy, or approves a new campaign.
    The archive digest binds the original producer archive, not current code.
    """
    root = Path(out)
    originals = {
        "spec": (root / "execution-spec.json", spec_sha256),
        "root": (root / "root-status.json", root_sha256),
        "archive": (Path(archive_path), archive_sha256),
    }
    for name, (path, digest) in originals.items():
        if hashlib.sha256(path.read_bytes()).hexdigest() != digest:
            raise ValueError(f"original {name} hash differs")
    result = verify_campaign(root)
    # Reject concurrent changes, even though this interface is post-exit only.
    for name, (path, digest) in originals.items():
        if hashlib.sha256(path.read_bytes()).hexdigest() != digest:
            raise ValueError(f"original {name} hash changed during review")
    return dict(
        verification_protocol="longmemeval-readonly-reuse@v2",
        verifier_sha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
        original_spec_sha256=spec_sha256,
        original_root_sha256=root_sha256,
        original_archive_sha256=archive_sha256,
        campaign_complete=result["complete"],
        planned_job_ids=[r["job_id"] for r in result["jobs"]],
        reuse_qa_job_ids=[
            r["job_id"]
            for r in result["jobs"]
            if r["status"] == "complete" and r["result"]["quality_status"] == "complete_verified"
        ],
        not_applicable_job_ids=[
            r["job_id"]
            for r in result["jobs"]
            if r["status"] == "complete"
            and r["result"]["quality_status"] == "not_applicable_context_overflow"
        ],
    )


