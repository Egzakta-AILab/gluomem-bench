def validate_chained_continuation_spec(spec, *, budget=None, ancestry=()):
    if spec.get("protocol") != CHAINED_PROTOCOL:
        raise ValueError("explicit chained protocol required")
    previous, prior, uncertainty = _load_chained_predecessor(
        spec["predecessor_binding"], budget=budget, ancestry=ancestry
    )
    if not isinstance(spec.get("launch_metadata"), dict):
        raise ValueError("complete frozen chain launch metadata required")
    if spec["dataset"] != previous["dataset"] or spec["judge_source"] != previous["judge_source"]:
        raise ValueError("chain source/profile/cap/native protocol drift")
    if hashlib.sha256(Path(spec["dataset"]["path"]).read_bytes()).hexdigest() != previous["dataset"]["sha256"]:
        raise ValueError("chain pinned dataset bytes differ")
    launch = _chain_launch_metadata(previous, spec["output_root"], spec["launch_metadata"])
    if spec["launch_metadata"] != launch:
        raise ValueError("complete frozen chain launch metadata differs")
    for key in ("runtime_root", "working_directory", "pythonpath", "execution_environment", "candidate_source_archive"):
        if spec.get(key) != launch[key]:
            raise ValueError("chain launch binding differs")
    mutable = {
        "runtime_root", "working_directory", "pythonpath", "execution_environment", "candidate_source_archive", "launch_metadata",
        "protocol",
        "output_root",
        "predecessor_binding",
        "prior_accounting",
        "prior_spend_uncertainty",
        "prior_resource_allowance",
        "semantic_delta_manifest",
        "semantic_bridge",
        "new_cohort",
        "cohorts",
        "jobs",
        "dispatch_job_ids",
        "files",
    }
    if any(spec.get(k) != v for k, v in previous.items() if k not in mutable):
        raise ValueError("chain source/profile/cap/native protocol drift")
    if spec.get("files") != frozen_inventory(spec["dataset"]["path"], spec["judge_source"]):
        raise ValueError("chain launch inventory/source binding differs")
    import sys

    old_runtime = Path(previous.get("runtime_root", "/__no_previous_runtime__")).resolve()
    current_runtime = Path(launch["runtime_root"])
    def external(items, private):
        return {str(Path(p["path"]).resolve()): p["sha256"] for p in items
                if not Path(p["path"]).resolve().is_relative_to(private)}
    old_external = external(previous["files"], old_runtime)
    new_external = external(spec["files"], current_runtime)
    # Dataset and scorer remain independently pinned semantic fields. They may
    # reside in the current private tree in authored fixtures, but not disappear.
    for key in ("dataset", "judge_source"):
        value = spec[key]["path"] if key == "dataset" else spec[key]
        old_external.pop(str(Path(value).resolve()), None)
        new_external.pop(str(Path(value).resolve()), None)
    # Private source projections are checked by the semantic bridge; package and
    # interpreter identities are invariant external inputs, not launch metadata.
    old_external = {p: h for p, h in old_external.items() if not Path(p).is_relative_to(current_runtime)}
    if old_external != new_external or str(Path(sys.executable).resolve()) not in old_external:
        raise ValueError("chain interpreter/package environment differs from predecessor")
    pins = {str(Path(item["path"]).resolve()): item["sha256"] for item in spec["files"]}
    for name, module in list(sys.modules.items()):
        if name == "gluomem" or name.startswith("gluomem.") or name == "gluomem_bench" or name.startswith("gluomem_bench."):
            source = getattr(module, "__file__", None)
            base = Path(launch["pythonpath"][1 if name.split(".")[0] == "gluomem" else 0])
            if source is None or not Path(source).resolve().is_relative_to(base):
                raise ValueError("chain actual import escapes private runtime")
            path = Path(source).resolve()
            expected = base.joinpath(*name.split("."))
            if path not in {expected.with_suffix(".py"), expected / "__init__.py"}:
                raise ValueError("chain actual import module location differs")
            if pins.get(str(path)) != hashlib.sha256(path.read_bytes()).hexdigest():
                raise ValueError("chain actual import missing from source inventory")
    root = Path(spec["output_root"]).resolve()
    if root.is_relative_to(Path(spec["predecessor_binding"]["root"]).resolve()):
        raise ValueError("chain output overlaps predecessor")
    rows = _chained_rows(previous, prior, root)
    cohort_key = (
        "repaired"
        if "repaired" not in previous["cohorts"]
        else "repaired_" + str(len(previous["cohorts"]))
    )
    label = spec["cohorts"].get(cohort_key)
    if (
        spec["jobs"] != rows
        or spec["dispatch_job_ids"] != [r["job_id"] for r in rows if r["disposition"] == "dispatch"]
        or spec["prior_accounting"] != prior["accounting"]
        or spec["prior_spend_uncertainty"] != uncertainty
        or spec["new_cohort"] != cohort_key
        or not isinstance(label, str)
        or not label
        or label in previous["cohorts"].values()
        or spec["cohorts"] != dict(previous["cohorts"], **{cohort_key: label})
        or spec["semantic_bridge"]
        != _chain_semantic_bridge(previous, spec["semantic_delta_manifest"])
    ):
        raise ValueError("exact chained rows/prior accounting/cohort/semantic binding differs")
    _validate_prior_resource_allowance(spec)
    return prior


