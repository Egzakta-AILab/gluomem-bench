def _chained_rows(previous_spec, previous, output_root):
    """Keep latest attempted identities latched; never reconstruct dispatch from v1."""
    import copy

    ids = [r["job_id"] for r in previous_spec["jobs"]]
    if len(ids) != len(set(ids)) or ids != [r["job_id"] for r in previous["jobs"]]:
        raise ValueError("exact unique predecessor row order required")
    rows = []
    for record, prior in zip(previous_spec["jobs"], previous["jobs"], strict=True):
        quality = prior.get("result", {}).get("quality_status")
        if prior["status"] == "complete" and quality in {
            "complete_verified",
            "not_applicable_context_overflow",
        }:
            disposition = "reuse_qa" if quality == "complete_verified" else "reuse_na"
        elif prior["status"] == "failed":
            disposition = "retained_failure"
        elif (
            prior["status"] in {"cancelled", "unrun"}
            and "result" not in prior
            and type(prior.get("calls", 0)) is int
            and prior.get("calls", 0) == 0
            and record["disposition"] == "dispatch"
            and record["prior_row"]["status"] in {"cancelled", "unrun"}
            and record["prior_row"].get("calls", 0) == 0
            and not Path(record["output"]).exists()
        ):
            disposition = "dispatch"
        else:
            raise ValueError("chain dispatch requires original and latest never-run identity")
        rows.append(
            dict(
                copy.deepcopy(record),
                disposition=disposition,
                prior_row=copy.deepcopy(prior),
                prior_cohort=prior["cohort"],
                output=str(Path(output_root) / "jobs" / record["job_id"])
                if disposition == "dispatch"
                else record["output"],
            )
        )
    return rows


def _chain_semantic_bridge(previous, manifest_binding):
    """Bind all benchmark/core algorithms, with an explicit reviewed guard delta."""
    manifest = json.loads(_read_bound(manifest_binding["path"], manifest_binding["sha256"]))
    version = manifest.get("protocol")
    if version not in {"longmemeval-reviewed-guard-delta@v1", "longmemeval-reviewed-guard-delta@v2"}:
        raise ValueError("explicit reviewed guard delta manifest required")
    privacy_v2 = version == "longmemeval-reviewed-guard-delta@v2"
    entries = manifest["files"]
    names = [e["relative_path"] for e in entries]
    allowed = {"suite_campaign.py", "rack.py", "embedding_runtime.py"}
    if privacy_v2:
        allowed |= {"parallel_campaign.py", "mem0.py"}
        if any(e.get("contract") != "longmemeval-privacy-guard-symbols@v2" for e in entries):
            raise ValueError("v2 manifest requires exact v2 symbol contracts")
    if not privacy_v2 and any(e.get("contract") is not None for e in entries):
        raise ValueError("legacy v1 manifest cannot import v2 symbol contracts")
    if len(names) != len(set(names)) or not set(names) <= allowed:
        raise ValueError("guard delta inventory differs")
    by_name = {e["relative_path"]: e for e in entries}
    # Keep the original bridge's core/compiled-prompt and reader/pairing gates.
    # Only suite_campaign can need a delta inside that bridge.
    original, _ = _continuation_original(previous["original_binding"])
    # Guard deltas are transitive through authenticated predecessors, whereas
    # core, prompts, extraction/reader/scorer/input/vector semantics stay v1-pinned.
    import copy

    baseline = copy.deepcopy(original)
    bridge_names = {"suite_campaign.py", "mem0.py"} if privacy_v2 else {"suite_campaign.py"}
    for name in bridge_names:
        suffix = "/gluomem_bench/bench/" + name
        latest = [f for f in previous["files"] if f["path"].replace("\\", "/").endswith(suffix)]
        if len(latest) != 1:
            raise ValueError("predecessor semantic guard pin missing")
        for item in baseline["files"]:
            if item["path"].replace("\\", "/").endswith(suffix):
                item["sha256"] = latest[0]["sha256"]
    bridge = _semantic_bridge(
        baseline, previous["original_binding"]["verifier_path"], guard_deltas=by_name
    )
    transport_names = ("rack.py", "embedding_runtime.py", "parallel_campaign.py") if privacy_v2 else ("rack.py", "embedding_runtime.py")
    for name in transport_names:
        pins = [
            f
            for f in previous["files"]
            if f["path"].replace("\\", "/").endswith("/gluomem_bench/bench/" + name)
        ]
        if len(pins) != 1:
            raise ValueError("predecessor transport/encoder binding missing")
        actual = Path(__file__).resolve().parent / name
        if name in by_name:
            if by_name[name]["old_sha256"] != pins[0]["sha256"]:
                raise ValueError("delta old bytes differ from predecessor")
            bridge.append(_verify_guard_delta(actual, by_name[name]))
        else:
            _read_bound(actual, pins[0]["sha256"])
            bridge.append(dict(pins[0], actual_path=str(actual)))
    return bridge


def _load_chained_predecessor(binding, *, budget=None, ancestry=()):
    """Authenticate the complete previous root, not a dispatch subset or v1 restart.

    v3 uses the externally byte-bound post-exit audit plus fresh native leaf
    replay. Later v4 roots recursively use their own read-only root verifier.
    The audit code is authenticated as evidence, never executed (it writes reports).
    """
    root = Path(binding["root"]).resolve()
    if str(root) in ancestry:
        raise ValueError("continuation chain cycle")

    def read(label, path=None):
        if budget is not None:
            budget.check()
        return _read_bound(path or binding[label + "_path"], binding[label + "_sha256"])

    spec = json.loads(read("spec", root / "execution-spec.json"))
    root_receipt = (
        root / "root-incomplete.json"
        if spec.get("protocol") == CHAINED_PROTOCOL and (root / "root-incomplete.json").exists()
        else root / "root-status.json"
    )
    result = json.loads(read("root", root_receipt))
    read("archive")
    approval = json.loads(read("approval"))
    review = json.loads(read("review"))
    if (
        read("approval", root / "independent-approval.json") != read("approval")
        or any(
            x.get("approved") is not True
            or x.get("blockers") != []
            or x.get("spec_sha256") != binding["spec_sha256"]
            or x.get("archive_sha256") != binding["archive_sha256"]
            for x in (approval, review)
        )
        or approval.get("parent_execution_authorized") is not True
        or approval.get("independent_review_sha256") != binding["review_sha256"]
    ):
        raise ValueError("predecessor review/approval binding differs")
    if spec["protocol"] == CHAINED_PROTOCOL:
        result_verified = verify_campaign(root, budget=budget, _ancestry=ancestry + (str(root),))
        if result_verified != result:
            raise ValueError("predecessor readback differs")
        return spec, result, spec["prior_spend_uncertainty"]
    if spec["protocol"] != CONTINUATION_PROTOCOL:
        raise ValueError("chain must start from stopped v3 checkpoint")
    read("auditor_code")
    audit = json.loads(read("audit_result"))
    receipt = json.loads(read("audit_receipt"))
    for path, digest in receipt["files"].items():
        _read_bound(path, digest)
    if (
        receipt.get("root_sha256") != binding["root_sha256"]
        or receipt.get("spec_sha256") != binding["spec_sha256"]
        or receipt.get("archive_sha256") != binding["archive_sha256"]
        or receipt["files"].get(binding["auditor_code_path"]) != binding["auditor_code_sha256"]
        or receipt["files"].get(binding["audit_result_path"]) != binding["audit_result_sha256"]
        or receipt.get("read_only_root_verified") is not True
        or audit.get("root_sha256") != binding["root_sha256"]
        or audit["cost"]["root_accounting"] != result["accounting"]
    ):
        raise ValueError("external readonly auditor evidence binding differs")
    for item in audit["bindings"]:
        if item.get("matches") is not True or item["expected_sha256"] != item["actual_sha256"]:
            raise ValueError("external audit binding not verified")
        if budget is not None:
            budget.check()
        _read_bound(item["path"], item["expected_sha256"])
    original, prior = _continuation_original(spec["original_binding"])
    reuse = replay_continuation_reuse(spec["original_binding"])
    expected = _continuation_rows(original, prior, reuse, spec["quality_failure_job_ids"], root)
    fields = (
        "sample_ids",
        "systems",
        "dataset",
        "config_overrides",
        "judge_source",
        "embedding_url",
        "embedding_recipe",
        "evidence_token_budget",
        "source_identifier_policy",
        "raw_chunk_chars",
    )
    if (
        any(spec[k] != original[k] for k in fields)
        or spec["jobs"] != expected
        or spec["reuse_receipt"] != reuse
        or spec["prior_accounting"] != prior["accounting"]
        or spec["profile"] != dict(original["profile"], timeout_seconds=600)
        or spec["campaign_policy"]
        != dict(original["campaign_policy"], max_workers=1, max_in_flight=1)
        or len(spec["jobs"]) != 3500
        or len(spec["cognee_unrun"]) != 500
        or spec["cohorts"]
        != dict(legacy="timeout120_parallel8", fresh="timeout600_serial1", pool_quality=False)
        or result.get("complete") is not False
        or result.get("execution_complete") is not False
        or result.get("publication") != "incomplete"
        or (root / "campaign-result.json").exists()
    ):
        raise ValueError("v3 full predecessor semantic/authority binding differs")
    view = dict(
        result,
        frozen_inputs=[dict(f, snapshot="frozen-inputs/" + f["sha256"]) for f in spec["files"]],
    )
    _replay_chained_predecessor_rows(root, spec, view, audit, budget)
    # A second read prevents a changing root being accepted after replay.
    read("spec", root / "execution-spec.json")
    read("root", root / "root-status.json")
    return spec, result, audit["cost"]["unreceipted_failure_boundary"]


def _replay_chained_predecessor_rows(root, spec, view, audit, budget):
    """Replay genuine incomplete v3 evidence with snapshot refs in memory only."""
    from dataclasses import asdict

    from gluomem_bench.bench.suite_campaign import verify_history

    ids = [r["job_id"] for r in spec["jobs"]]
    if ids != [r["job_id"] for r in view["jobs"]] or ids != [
        r["job_id"] for r in audit["row_dispositions"]
    ]:
        raise ValueError("audited exact predecessor matrix differs")
    for item in spec["files"]:
        _pinned_snapshot(root, spec, view, item["path"])
    native = _native_review_inputs(root, spec, view)
    cfg, profile, samples, conversations, extractor = native
    fresh_calls = 0
    for record, row, ledger in zip(
        spec["jobs"], view["jobs"], audit["row_dispositions"], strict=True
    ):
        if budget is not None:
            budget.check()
        legacy = record["disposition"] != "dispatch"
        source_root = Path(spec["original_binding"]["original_root"]) if legacy else root
        if Path(record["output"]).resolve() != (source_root / "jobs" / record["job_id"]).resolve():
            raise ValueError("predecessor leaf normal path differs")
        if (
            ledger["status"] != row["status"]
            or ledger["cohort"] != row["cohort"]
            or ledger["calls"] != row.get("calls", 0)
            or ledger["quality_status"] != row.get("result", {}).get("quality_status")
            or ledger["sample_id"] != record["sample_id"]
            or ledger["system"] != record["system"]
        ):
            raise ValueError("auditor row disposition differs")
        if row.get("artifact_sha256") != _job_artifacts(source_root, record, budget):
            raise ValueError("exact predecessor artifact membership differs")
        if legacy:
            if row != dict(record["prior_row"], disposition=record["disposition"], cohort="legacy"):
                raise ValueError("predecessor original row changed")
            continue  # authenticated unchanged v2 QA/N/A replay already performed
        actual_calls = _recorded_calls(Path(record["output"]))
        if actual_calls != row.get("calls", 0) or type(row.get("calls", 0)) is not int:
            raise ValueError("predecessor trace/scheduler accounting differs")
        fresh_calls += actual_calls
        if row["status"] == "complete" and row["result"]["quality_status"] == "complete_verified":
            sample = samples[record["sample_id"]]
            expected = dict(
                dataset=spec["dataset"]["name"], system=record["system"], sample_ids=[sample.id]
            )
            leaf = Path(record["output"])
            if json.loads((leaf / "effective-config.json").read_bytes()) != cfg.model_dump(
                mode="json"
            ) or json.loads((leaf / "predictions.json").read_bytes())[0]["sample"] != json.loads(
                json.dumps(asdict(sample))
            ):
                raise ValueError("predecessor source/profile reconstruction differs")
            if record["system"] == "mem0":
                from gluomem_bench.bench.mem0 import _mem0_digest, _session_messages

                expected.update(
                    mem0_source_inputs_sha256=_mem0_digest(
                        [
                            dict(
                                session_index=s.index,
                                session_date=s.date_time.isoformat(),
                                messages=_session_messages(s),
                            )
                            for s in conversations[sample.conv_id].sessions
                        ]
                    ),
                    mem0_extractor_system_sha256=extractor,
                    profile_sha256=hashlib.sha256(profile.model_dump_json().encode()).hexdigest(),
                    dataset_sha256=spec["dataset"]["sha256"],
                )
            if row["result"].get("expected_job") != expected:
                raise ValueError("predecessor reconstructed QA binding differs")
            summary = verify_history(
                leaf,
                expected_job=expected,
                require_real=True,
                judge_source=_pinned_snapshot(root, spec, view, spec["judge_source"]),
            )
            if (
                summary != row["result"]["summary"]
                or json.loads((leaf / "usage.json").read_bytes())["generation_calls"]
                != actual_calls
            ):
                raise ValueError("predecessor exact QA replay differs")
        elif row["status"] == "complete":
            _verify_continuation_na(root, spec, record, row, native)
        elif row["status"] not in {"failed", "cancelled", "unrun"}:
            raise ValueError("predecessor nonterminal row")
        if row["status"] in {"cancelled", "unrun"} and (
            actual_calls or Path(record["output"]).exists()
        ):
            raise ValueError("predecessor cancelled row was attempted")
    accounting, prior = view["accounting"], spec["prior_accounting"]
    import math

    if (
        accounting["calls"] != prior["calls"] + fresh_calls
        or accounting["new_calls"] != fresh_calls
        or accounting["prior_calls"] != prior["calls"]
        or accounting["prior_elapsed_seconds"] != prior["elapsed_seconds"]
        or not math.isfinite(accounting["elapsed_seconds"])
        or accounting["new_elapsed_seconds"] < 0
        or accounting["elapsed_seconds"]
        != prior["elapsed_seconds"] + accounting["new_elapsed_seconds"]
    ):
        raise ValueError("predecessor cumulative accounting differs")
    progress = json.loads((root / "coordination/progress.json").read_bytes())
    cleaned = [
        {k: v for k, v in r.items() if k not in {"artifact_sha256", "disposition", "cohort"}}
        for rec, r in zip(spec["jobs"], view["jobs"], strict=True)
        if rec["disposition"] == "dispatch"
    ]
    if progress["jobs"] != cleaned:
        raise ValueError("predecessor scheduler evidence differs")


def _recorded_calls(leaf):
    calls = 0
    for name in ("calls.jsonl", "production-raw.jsonl"):
        path = leaf / name
        for raw in path.read_bytes().splitlines() if path.exists() else []:
            if not raw:
                continue
            receipt = json.loads(raw)
            calls += (
                int(
                    receipt.get("method") == "POST"
                    and receipt.get("url", "").endswith("/chat/completions")
                )
                if name == "calls.jsonl"
                else int("ordinal" in receipt)
            )
    return calls


def _chain_read_only_assets(binding, namespace):
    """Authenticate retained native-cache assets; never use their tree for writes."""
    import zipfile

    if binding is None:
        return []
    namespace = Path(namespace).resolve()
    if Path(binding["path"]).resolve() != namespace / "native-cache-assets.json":
        raise ValueError("read-only asset manifest escapes declared namespace")
    manifest = json.loads(_read_bound(binding["path"], binding["sha256"]))
    source = manifest["source_archive"]
    _read_bound(source["path"], source["sha256"])
    result, seen = [], set()
    with zipfile.ZipFile(source["path"]) as archive:
        for item in manifest["files"]:
            relative = Path(item["relative_path"])
            path = (namespace / "native-cache-assets" / relative).resolve()
            if relative.is_absolute() or ".." in relative.parts or not path.is_relative_to(namespace / "native-cache-assets") or str(path) in seen:
                raise ValueError("read-only native asset path escape/duplicate")
            seen.add(str(path))
            material = _read_bound(path, item["sha256"])
            if archive.read(item["archive_member"]) != material:
                raise ValueError("read-only native asset source archive differs")
            result.append(dict(item, path=str(path), access="read-only"))
    return result


def _seed_chain_cache_assets(spec):
    """Copy authenticated read-only assets into the declared writable cache only."""
    launch = spec["launch_metadata"]
    files = _chain_read_only_assets(launch.get("read_only_assets"), launch["namespace_root"])
    root = Path(spec["output_root"]).resolve()
    cache = Path(spec["execution_environment"]["FASTEMBED_CACHE_PATH"]).resolve()
    if not cache.is_relative_to(root) or cache == root:
        raise ValueError("native cache write escapes declared output")
    for item in files:
        destination = (cache / item["relative_path"]).resolve()
        if not destination.is_relative_to(cache):
            raise ValueError("native asset cache write escape")
        material = _read_bound(item["path"], item["sha256"])
        destination.parent.mkdir(parents=True, exist_ok=True)
        with destination.open("xb") as target:
            target.write(material)


def _chain_launch_metadata(previous, output_root, launch_metadata=None):
    """Canonical launch-only metadata, derived from this private producer, not cwd."""
    import copy

    runtime = Path(__file__).resolve().parents[3]
    namespace = runtime.parent
    if runtime.name != "runtime":
        raise ValueError("chain launch requires a private runtime; no ambient live fallback")
    supplied = launch_metadata or {"namespace_root": str(namespace)}
    if Path(supplied["namespace_root"]).resolve() != namespace:
        raise ValueError("chain launch namespace differs from actual private runtime")
    root = Path(output_root).resolve()
    protected = [previous.get("output_root"), previous.get("runtime_root"),
                 previous.get("original_binding", {}).get("original_root")]
