def validate_continuation_spec(spec):
    """Full-scope continuation gate. It never weakens the legacy Cartesian gate."""
    from collections import Counter

    if spec.get("protocol") != CONTINUATION_PROTOCOL:
        raise ValueError("explicit continuation protocol required")
    old, prior = _continuation_original(spec["original_binding"])
    expected_profile = dict(old["profile"], timeout_seconds=600)
    policy = dict(old["campaign_policy"], max_workers=1, max_in_flight=1)
    fields = (
        "sample_ids",
        "systems",
        "dataset",
        "config_overrides",
        "judge_source",
        "embedding_url",
        "embedding_recipe",
        "evidence_token_budget",
        "source_identifier_policy",
        "raw_chunk_chars",
    )
    if (
        any(spec[k] != old[k] for k in fields)
        or spec["profile"] != expected_profile
        or spec["campaign_policy"] != policy
        or old["profile"]["timeout_seconds"] != 120
        or old["campaign_policy"]["max_workers"] != 8
        or spec["prior_accounting"] != prior["accounting"]
        or spec["cohorts"]
        != {"legacy": "timeout120_parallel8", "fresh": "timeout600_serial1", "pool_quality": False}
    ):
        raise ValueError("continuation semantic/profile/prior accounting binding differs")
    expected = _continuation_rows(
        old, prior, spec["reuse_receipt"], spec["quality_failure_job_ids"], spec["output_root"]
    )
    if spec["jobs"] != expected or spec["dispatch_job_ids"] != [
        r["job_id"] for r in expected if r["disposition"] == "dispatch"
    ]:
        raise ValueError("exact continuation rows/dispositions/order differ")
    counts = Counter(r["disposition"] for r in expected)
    if counts != dict(
        reuse_qa=25,
        reuse_na=5,
        retained_quality_failure=5,
        retained_unresolved_failure=8,
        dispatch=3457,
    ):
        raise ValueError("full continuation disposition counts differ")
    if spec["cognee_unrun"] != [
        dict(sample_id=s, system="cognee", status="unrun", admitted=False)
        for s in old["sample_ids"]
    ]:
        raise ValueError("all500 separate Cognee unrun rows required")
    if spec["semantic_bridge"] != _semantic_bridge(old, spec["original_binding"]["verifier_path"]):
        raise ValueError("semantic bridge differs")
    reuse = replay_continuation_reuse(spec["original_binding"])
    if reuse != spec["reuse_receipt"]:
        raise ValueError("read-only reuse replay differs")
    return reuse


def validate_full_spec(spec, dataset_order):
    from gluomem_bench.bench.parallel_campaign import CampaignPolicy
    from gluomem_bench.bench.rack import RackProfile

    ids, systems = spec["sample_ids"], spec["systems"]
    if len(dataset_order) != 500 or len(set(dataset_order)) != 500 or ids != list(dataset_order):
        raise ValueError("full scope requires exactly dataset-ordered 500 native QA IDs")
    if len(systems) != 7 or set(systems) != set(SUPPORTED_SYSTEMS):
        raise ValueError("all seven supported systems required")
    profile = RackProfile.model_validate(spec["profile"])
    if profile.profile_version != "role-budgets-v6" or profile.output_budget("answer") != 4096:
        raise ValueError("full scope requires V6 explicit reader4096")
    if (
        spec.get("evidence_token_budget") != 4096
        or spec.get("source_identifier_policy") != "opaque-ordinal-turns@v1"
    ):
        raise ValueError(
            "full scope requires shared4096 reader and opaque audit-only source mappings"
        )
    policy = CampaignPolicy(**spec["campaign_policy"])
    if policy.stop_on_failure or policy.max_workers > 8 or policy.max_in_flight > 32:
        raise ValueError("full scope requires isolated jobs, <=8 workers and <=32 in-flight")
    matrix = [(r["sample_id"], r["system"]) for r in spec["jobs"]]
    if matrix != [(sample, system) for sample in ids for system in systems]:
        raise ValueError("exact complete dataset-ordered full matrix required")
    jobs = spec["jobs"]
    if (
        len({j["job_id"] for j in jobs}) != len(jobs)
        or len({str(Path(j["output"]).resolve()) for j in jobs}) != len(jobs)
        or any(
            j["history_id"] != j["sample_id"]
            or j["call_budget"] != profile.max_generation_calls
            or j["seconds_budget"] != profile.max_run_seconds
            for j in jobs
        )
    ):
        raise ValueError("duplicate job identities or different whole-history budgets")
    root = Path(spec["output_root"]).resolve()
    if any(not Path(j["output"]).resolve().is_relative_to(root / "jobs") for j in jobs):
        raise ValueError("job output escapes dedicated matrix job root")
    return len(jobs)


