def _continuation_rows(original_spec, original, reuse, quality_failures, output_root):
    """Lossless ordered partition: no failed attempt is eligible for dispatch."""
    import copy

    if [r["job_id"] for r in original["jobs"]] != [r["job_id"] for r in original_spec["jobs"]]:
        raise ValueError("original row ordering differs")
    qa, na, quality = (
        set(reuse["reuse_qa_job_ids"]),
        set(reuse["not_applicable_job_ids"]),
        set(quality_failures),
    )
    failed = {r["job_id"] for r in original["jobs"] if r["status"] == "failed"}
    if not quality <= failed or qa & na or (qa | na) & failed:
        raise ValueError("invalid reuse/failure dispositions")
    rows = []
    for record, prior in zip(original_spec["jobs"], original["jobs"], strict=True):
        key = record["job_id"]
        if key in qa:
            disposition = "reuse_qa"
        elif key in na:
            disposition = "reuse_na"
        elif key in failed:
            disposition = (
                "retained_quality_failure" if key in quality else "retained_unresolved_failure"
            )
        elif prior["status"] in {"unrun", "cancelled"} and prior.get("calls", 0) == 0:
            disposition = "dispatch"
        else:
            raise ValueError("dispatch requires original never-run row")
        rows.append(
            dict(
                copy.deepcopy(record),
                disposition=disposition,
                prior_row=copy.deepcopy(prior),
                output=str(Path(output_root) / "jobs" / key)
                if disposition == "dispatch"
                else record["output"],
            )
        )
    return rows


