    spec["launch_metadata"] = launch
    for key in ("runtime_root", "working_directory", "pythonpath", "execution_environment", "candidate_source_archive"):
        spec[key] = copy.deepcopy(launch[key])
    spec["dispatch_job_ids"] = [r["job_id"] for r in spec["jobs"] if r["disposition"] == "dispatch"]
    spec["files"] = frozen_inventory(spec["dataset"]["path"], spec["judge_source"])
    validate_chained_continuation_spec(spec)
